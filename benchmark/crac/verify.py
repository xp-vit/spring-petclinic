#!/usr/bin/env python3
"""Recompute every number in results-summary-crac.md from raw run dirs.

Usage: python3 -I verify.py <results-root> > verify-output.md
<results-root> holds aws-v2/, aws-v2-crac/, aws-v2-peak/, aws-crac-retest/.
Stdlib only (+ `zstd` binary for *.csv.zst). Prints markdown.
"""
import json, pathlib, statistics, subprocess, sys

R = pathlib.Path(sys.argv[1])
V = ["jvm", "crac-jvm", "crac", "crac-onrefresh", "native"]
MIB = 1024 * 1024


def txt(p):
    try:
        return p.read_text().strip()
    except FileNotFoundError:
        return None


def probe(p):
    """first-200 ts minus probe start minus the script's fixed `sleep 2` (approximation)."""
    if not p.exists():
        return None
    rows = [l.split() for l in p.read_text().split("\n") if l.strip()]
    t0 = float(rows[0][0])
    t200 = next((float(t) for t, c in rows if c == "200"), None)
    gaps = [float(b[0]) - float(a[0]) for a, b in zip(rows, rows[1:])]
    return (None if t200 is None else round((t200 - t0 - 2) * 1000), round(statistics.median(gaps) * 1000), len(rows))


def peak(d, v, n=5):
    out = []
    for i in range(1, n + 1):
        f = d / f"{v}-peak-rps-iter{i}-summary.json"
        if not f.exists():
            out.append((i, None)); continue
        m = json.loads(f.read_text())["metrics"]
        dur = m["http_req_duration"]
        out.append((i, dict(rps=m["http_reqs"]["rate"], p95=dur["p(95)"], p99=dur["p(99)"],
                            fail=m["http_req_failed"]["value"], n=m["http_reqs"]["count"])))
    return out


def max_mem(f):
    if not f.exists():
        return None
    raw = subprocess.run(["zstd", "-dc", str(f)], capture_output=True, text=True).stdout
    vals = [int(l.split(",")[2]) for l in raw.split("\n")[1:] if l.count(",") == 2]
    return max(vals) if vals else None


print("# CRaC raw-data verification (generated by benchmark/crac/verify.py)\n")
print("## Cold start (docker run -> first /vets 200). n = 1 per variant per run dir\n")
print("| run dir | variant | cold-start-ms.txt | probe-log estimate ms | probe interval ms | spring/warp log |")
print("|---|---|---:|---:|---:|---|")
for d in ["aws-v2-crac", "aws-v2"]:
    for v in V:
        c = txt(R / d / f"{v}-cold-start-ms.txt")
        if c is None:
            print(f"| {d} | {v} | absent | | | |"); continue
        pr = probe(R / d / f"{v}-cold-probe.log")
        log = txt(R / d / f"{v}-spring-started-s.txt")
        log = f"Started {log} s" if log else (f"warp restore {txt(R/d/f'{v}-restore-ms.txt')} ms" if txt(R/d/f'{v}-restore-ms.txt') else "")
        print(f"| {d} | {v} | {c} | {pr[0] if pr else ''} | {pr[1] if pr else ''} | {log} |")

print("\n## Peak RPS (k6 ramping-arrival-rate), per iteration\n")
print("| run dir | variant | iter | rps | p95 s | p99 s | fail % |")
print("|---|---|---:|---:|---:|---:|---:|")
best = {}
for d in ["aws-v2-crac", "aws-v2", "aws-v2-peak"]:
    for v in (V if d != "aws-v2" else ["native"]):
        for i, r in peak(R / d, v):
            if r is None:
                if (R / d / f"{v}-peak-rps-iter{i}-output.txt").exists():
                    print(f"| {d} | {v} | {i} | no summary.json | | | |")
                continue
            print(f"| {d} | {v} | {i} | {r['rps']:.1f} | {r['p95']/1000:.2f} | {r['p99']/1000:.2f} | {r['fail']*100:.1f} |")
            if r["fail"] < 0.01 and r["rps"] > best.get((d, v), {"rps": 0})["rps"]:
                best[(d, v)] = r
print("\nBest clean (fail<1%) iteration per variant, and median of all 5 iterations:\n")
for (d, v), r in best.items():
    med = statistics.median(x["rps"] for _, x in peak(R / d, v) if x)
    print(f"- {d} {v}: best {r['rps']:.1f} rps (p95 {r['p95']/1000:.2f} s, p99 {r['p99']/1000:.2f} s); median of 5 {med:.1f} rps")

print("\n## Retest 2x2 (aws-crac-retest)\n")
print("| cell | iters with summary | rps/fail per iter | best clean rps | median rps | peak mem MiB |")
print("|---|---|---|---:|---:|---:|")
for cell in ["crac-jvm-512m", "crac-jvm-768m", "crac-512m", "crac-768m"]:
    v = cell.rsplit("-", 1)[0]
    rs = [(i, r) for i, r in peak(R / "aws-crac-retest" / cell, v, 3) if r]
    mm = max_mem(R / "aws-crac-retest" / cell / f"{cell}-stats-peak.csv.zst")
    med = statistics.median(r["rps"] for _, r in rs)
    rates = ", ".join(f"i{i}:{r['rps']:.0f}/{r['fail']*100:.0f}%f" for i, r in rs)
    clean = [r["rps"] for _, r in rs if r["fail"] < 0.01]
    print(f"| {cell} | {len(rs)} | {rates} | {max(clean):.0f} | {med:.0f} | {mm/MIB:.0f} |" if clean else f"| {cell} | {len(rs)} | {rates} | none clean | n/a | {mm/MIB if mm else 0:.0f} |")

print("\n## Container memory from docker-stats CSVs (first sample = cold, max = peak)\n")
for v in V:
    d = "aws-v2" if v == "native" else "aws-v2-crac"
    for ph in ["mixed", "peak"]:
        f = R / d / f"{v}-stats-{ph}.csv.zst"
        if not f.exists():
            continue
        raw = subprocess.run(["zstd", "-dc", str(f)], capture_output=True, text=True).stdout
        vals = [int(l.split(",")[2]) for l in raw.split("\n")[1:] if l.count(",") == 2]
        print(f"- {d}/{v} {ph}: first {vals[0]/MIB:.0f} MiB, max {max(vals)/MIB:.0f} MiB, n={len(vals)}")

print("\n## Sizes (bytes -> MiB)\n")
for d in ["aws-v2-crac", "aws-v2"]:
    for f in sorted((R / d).glob("*-bytes.txt")):
        b = int(txt(f))
        print(f"- {d}/{f.name}: {b} B = {b/MIB:.1f} MiB = {b/1e6:.1f} MB")
for d in ["aws-v2-crac"]:
    for f in sorted((R / d).glob("*checkpoint-create-s.txt")):
        print(f"- {d}/{f.name}: {txt(f)} s")
